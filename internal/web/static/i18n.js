const escapePattern=value=>value.replace(/[.*+?^${}()|[\]\\]/g,'\\$&');
const literalPattern=new RegExp(Object.keys(translations).filter(key=>!/%[ds]/.test(key)).sort((a,b)=>b.length-a.length).map(escapePattern).join('|'),'g');
const messagePatterns=Object.entries(translations).filter(([key])=>/%[ds]/.test(key)).map(([key,value])=>({pattern:new RegExp('^'+key.split(/%[ds]/).map(escapePattern).join('(.*?)')+'$'),value}));
function t(value){
  if(Object.hasOwn(messageUpdates,value))value=messageUpdates[value];
  if(language!=='en')return value;
  if(Object.hasOwn(translations,value))return translations[value];
  for(const entry of messagePatterns){const match=String(value).match(entry.pattern);if(match){let i=0;return entry.value.replace(/%[ds]/g,()=>match[++i]);}}
  return value;
}
function translateLiteral(value){return language==='en'?value.replace(literalPattern,key=>translations[key]):value;}
// Static template segments alone are translated; interpolated user data is intact.
function tr(strings,...values){return strings.reduce((out,part,i)=>out+translateLiteral(part)+(i<values.length?values[i]:''),'');}
function localizeResponse(value){
  if(!value||typeof value!=='object')return value;
  if(Array.isArray(value)){value.forEach(localizeResponse);return value;}
  for(const [key,item] of Object.entries(value)){
    if(['error','last_error','message'].includes(key)&&typeof item==='string')value[key]=t(item);
    else if(['notices','warnings'].includes(key)&&Array.isArray(item))value[key]=item.map(t);
    else if(item&&typeof item==='object')localizeResponse(item);
  }
  return value;
}
function initializeLanguage(){
  document.documentElement.lang=language;
  const walker=document.createTreeWalker(document.documentElement,NodeFilter.SHOW_TEXT);
  while(walker.nextNode()){
    const node=walker.currentNode;
    if(!['SCRIPT','STYLE'].includes(node.parentElement?.tagName))node.nodeValue=translateLiteral(node.nodeValue);
  }
  for(const element of document.querySelectorAll('[placeholder],[aria-label],[title]')){
    for(const attribute of ['placeholder','aria-label','title'])if(element.hasAttribute(attribute))element.setAttribute(attribute,translateLiteral(element.getAttribute(attribute)));
  }
  for(const picker of document.querySelectorAll('.language-select')){
    picker.value=language;
    picker.addEventListener('change',()=>{try{localStorage.setItem('language',picker.value);}catch{}location.reload();});
  }
  for(const button of document.querySelectorAll('.language-toggle')){
    const next=language==='en'?'zh-Hant':'en';
    button.textContent=next==='en'?'English':'繁體中文';
    button.lang=next;
    button.setAttribute('aria-label',t(next==='en'?'切換為英文':'切換為繁體中文'));
    button.addEventListener('click',()=>{try{localStorage.setItem('language',next);}catch{}location.reload();});
  }
}
